export function localizeText(text: string, lang: Lang): string {
  if (lang === 'en') return text
  const sharedKey = (Object.keys(englishMessages) as MessageKey[])
    .find((key) => englishMessages[key] === text)
  return localizedContent[lang][text]
    ?? siteTranslations[lang][text]
    ?? (sharedKey ? messages[lang][sharedKey] : undefined)
    ?? text
}

export function localizeValue<T>(value: T, lang: Lang): T {
  if (typeof value === 'string') return localizeText(value, lang) as T
  if (Array.isArray(value)) return value.map((item) => localizeValue(item, lang)) as T
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, localizeValue(item, lang)]),
    ) as T
  }
  return value
}
